//! The rulebook: what counts as disposable build output, and when it is safe to
//! assume so.
//!
//! Every rule carries a [`Marker`] guard. A directory named `target` is only
//! treated as Rust build output when it sits next to a `Cargo.toml`; a stray
//! `target/` full of source code is never touched. This is the whole safety
//! story of `moltdisk` in one type.

/// A category of disposable output, used for grouping and `--kind` filtering.
pub struct Kind {
    pub id: &'static str,
    pub label: &'static str,
    pub blurb: &'static str,
    /// How this category is rebuilt from source. Printed by `moltdisk why`, and the
    /// reason we are willing to call the directory disposable at all.
    pub rebuild: &'static str,
    /// Participates in a default `moltdisk` run without any `--kind` flag.
    pub default: bool,
}

