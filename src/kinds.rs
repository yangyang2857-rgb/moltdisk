/// Directories that are never worth descending into while hunting.
pub const SKIP_DIRS: &[&str] = &[".git", ".hg", ".svn", ".Trash"];

/// Resolve a directory name to a rule, given the sibling file names of the
/// directory that contains it.
pub fn rule_for_dir(name: &str, siblings: &[String]) -> Option<&'static Rule> {
    RULES
        .iter()
        .filter(|r| r.is_dir && r.name == name)
        .find(|r| marker_holds(&r.marker, siblings))
}

pub fn rule_for_file(name: &str, siblings: &[String]) -> Option<&'static Rule> {
    RULES
        .iter()
        .filter(|r| !r.is_dir && r.name == name)
        .find(|r| marker_holds(&r.marker, siblings))
}

/// Every rule whose name matches, in table order. `moltdisk why` uses this to show
/// what was considered, not just what won.
pub fn rules_for(name: &str, is_dir: bool) -> Vec<&'static Rule> {
    RULES
        .iter()
        .filter(|r| r.is_dir == is_dir && r.name == name)
        .collect()
}

/// What satisfied a marker. `Some("")` means the name alone was enough;
/// `Some(file)` names the sibling that satisfied it; `None` means nothing did.
pub fn marker_evidence(marker: &Marker, siblings: &[String]) -> Option<String> {
    match marker {
        Marker::Any => Some(String::new()),
        Marker::Files(required) => siblings
            .iter()
            .find(|s| required.contains(&s.as_str()))
            .cloned(),
        Marker::Suffix(suffixes) => siblings
            .iter()
            .find(|s| suffixes.iter().any(|suffix| s.ends_with(suffix)))
            .cloned(),
    }
}

/// Human-readable description of what a marker demands.
pub fn marker_wants(marker: &Marker) -> String {
    match marker {
        Marker::Any => "nothing — the name is self-evident".to_string(),
        Marker::Files(files) => files.join(" or "),
        Marker::Suffix(suffixes) => format!("a file ending in {}", suffixes.join(" / ")),
    }
}

fn marker_holds(marker: &Marker, siblings: &[String]) -> bool {
    marker_evidence(marker, siblings).is_some()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn siblings(names: &[&str]) -> Vec<String> {
        names.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn trusts_self_evident_dirs() {
        assert_eq!(
            rule_for_dir("node_modules", &siblings(&[])).unwrap().kind,
            "node"
        );
    }

    #[test]
    fn target_needs_a_project_marker() {
        assert!(rule_for_dir("target", &siblings(&[])).is_none());
        assert_eq!(
            rule_for_dir("target", &siblings(&["Cargo.toml"]))
                .unwrap()
                .kind,
            "rust"
        );
        assert_eq!(
            rule_for_dir("target", &siblings(&["pom.xml"]))
                .unwrap()
                .kind,
            "jvm"
        );
    }

    #[test]
    fn suffix_markers_work() {
        assert_eq!(
            rule_for_dir("obj", &siblings(&["App.csproj"]))
                .unwrap()
                .kind,
            "dotnet"
        );
        assert!(rule_for_dir("obj", &siblings(&["main.rs"])).is_none());
    }

    #[test]
    fn every_rule_points_at_a_real_kind() {
        for rule in RULES {
            assert!(kind(rule.kind).is_some(), "unknown kind: {}", rule.kind);
        }
    }
}
