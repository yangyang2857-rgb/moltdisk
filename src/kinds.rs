pub fn kind(id: &str) -> Option<&'static Kind> {
    KINDS.iter().find(|k| k.id == id)
}

/// What must be true before a name match is trusted.
#[derive(Clone, Copy)]
pub enum Marker {
    /// The name is self-evidently disposable (`node_modules`, `__pycache__`).
    Any,
    /// One of these files must sit in the same directory as the candidate.
    Files(&'static [&'static str]),
    /// A file with one of these suffixes must sit in the same directory.
    Suffix(&'static [&'static str]),
}

pub struct Rule {
    /// Directory or file name to match.
    pub name: &'static str,
    /// Owning [`Kind::id`].
    pub kind: &'static str,
    pub marker: Marker,
    /// Included by default.
    pub default: bool,
    /// `true` for directories, `false` for single files.
    pub is_dir: bool,
}

const NODE: Marker = Marker::Any;
const PY: Marker = Marker::Any;

